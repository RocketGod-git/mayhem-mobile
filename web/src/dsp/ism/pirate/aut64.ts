/**
 * Port of ProtoPirate protocols/aut64.c (decrypt and unpack; GPL-3.0). Twin of pirate/PPAut64.kt. AUT64, 12 rounds,
 * 8-byte block (Garcia et al., USENIX Security 2016). Encrypt is encoder-only and does not ship.
 */
export class PPAut64Key {
  index = 0;
  readonly key = new Array<number>(8).fill(0);
  readonly pbox = new Array<number>(8).fill(0);
  readonly sbox = new Array<number>(16).fill(0);
}

