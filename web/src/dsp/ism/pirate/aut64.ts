// Key nibbles are masked to 0..15 where C indexes tables with them: the C has no bounds check (validations off),
// but every key unpacked from nibbles is already in range, so the mask never changes a result.
const keyNibble = (k: PPAut64Key, nibble: number, table: number[], iteration: number): number =>
  tableOffset[((k.key[table[iteration]] << 4) & 0xFF) | nibble];

function roundKey(k: PPAut64Key, state: number[], r: number): number {
  let hi = 0, lo = 0;
  for (let i = 0; i < BLOCK_SIZE - 1; i++) {
    hi ^= keyNibble(k, state[i] >>> 4, tableUn[r], i);
    lo ^= keyNibble(k, state[i] & 0x0F, tableLn[r], i);
  }
  return ((hi << 4) | lo) & 0xFF;
}

const finalByteNibble = (k: PPAut64Key, table: number[]): number => (tableSub[k.key[table[BLOCK_SIZE - 1]] & 0x0F] << 4) & 0xFF;

const decryptFinalByteNibble = (k: PPAut64Key, nibble: number, table: number[], result: number): number =>
  tableOffset[((result ^ nibble) + finalByteNibble(k, table)) & 0xFF];

function decryptCompress(k: PPAut64Key, state: number[], r: number): number {
  const rk = roundKey(k, state, r);
  const hi = decryptFinalByteNibble(k, state[BLOCK_SIZE - 1] >>> 4, tableUn[r], rk >>> 4);
  const lo = decryptFinalByteNibble(k, state[BLOCK_SIZE - 1] & 0x0F, tableLn[r], rk & 0x0F);
  return ((hi << 4) | lo) & 0xFF;
}

const substitute = (k: PPAut64Key, b: number): number => ((k.sbox[b >>> 4] << 4) & 0xFF) | k.sbox[b & 0x0F];

function permuteBytes(k: PPAut64Key, state: number[]): void {
  const result = new Array<number>(8).fill(0);
  for (let i = 0; i < 8; i++) result[k.pbox[i] & 7] = state[i];
  for (let i = 0; i < 8; i++) state[i] = result[i];
}

function permuteBits(k: PPAut64Key, b: number): number {
  let result = 0;
  for (let i = 0; i < 8; i++) if (b & (1 << i)) result |= 1 << (k.pbox[i] & 7);
  return result;
}

export const PPAut64 = {
  NUM_ROUNDS, BLOCK_SIZE, PACKED_KEY_SIZE: 16,

  /** aut64_decrypt: one 8-byte block in place (message[0..7]). */
  decrypt(k: PPAut64Key, message: number[]): void {
    for (let i = NUM_ROUNDS - 1; i >= 0; i--) {
      message[BLOCK_SIZE - 1] = substitute(k, message[BLOCK_SIZE - 1]);
      message[BLOCK_SIZE - 1] = permuteBits(k, message[BLOCK_SIZE - 1]);
      message[BLOCK_SIZE - 1] = substitute(k, message[BLOCK_SIZE - 1]);
      message[BLOCK_SIZE - 1] = decryptCompress(k, message, i);
      permuteBytes(k, message);
    }
  },

  /** aut64_unpack: a 16-byte packed key (index, 8 key nibbles, 8 x 3-bit pbox, 16 sbox nibbles). */
  unpack(src: number[]): PPAut64Key {
    const d = new PPAut64Key();
    d.index = src[0];
    for (let i = 0; i < 4; i++) { d.key[i * 2] = src[i + 1] >>> 4; d.key[i * 2 + 1] = src[i + 1] & 0xF; }
    let pbox = (src[5] << 16) | (src[6] << 8) | src[7];
    for (let i = 7; i >= 0; i--) { d.pbox[i] = pbox & 0x7; pbox >>>= 3; }
    for (let i = 0; i < 8; i++) { d.sbox[i * 2] = src[i + 8] >>> 4; d.sbox[i * 2 + 1] = src[i + 8] & 0xF; }
    return d;
  },
};
